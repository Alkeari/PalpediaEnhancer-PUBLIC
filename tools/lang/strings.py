def main() -> None:
    out_dir = Path(__file__).resolve().parents[2] / "Assets" / "lang"
    out_dir.mkdir(parents=True, exist_ok=True)
    for code, table in L.items():
        missing = [k for k in KEYS if k not in table]
        extra = [k for k in table if k not in KEYS]
        if missing or extra:
            raise SystemExit(f"{code}: missing {missing} extra {extra}")
        lines = [f"# Palpedia Enhancer UI strings ({code}). key=value, UTF-8. Missing keys fall back to English."]
        lines += [f"{k}={table[k]}" for k in KEYS]
        (out_dir / f"{code}.ini").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {code}.ini ({len(KEYS)} keys)")


if __name__ == "__main__":
    main()
